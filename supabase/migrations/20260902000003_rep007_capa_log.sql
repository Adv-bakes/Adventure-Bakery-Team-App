-- REP-007 - CAPA Log. D-07.
--
-- The register. FSQM-009 Part 9 calls it the answer to "show me your open corrective actions", and
-- it is the trending input 2.1.2.1 (iv) and 2.1.3.2 want. A derived report over FRM-007's responses
-- using the engine in src/lib/formReport.ts: type='report', NO entries of its own, so it does not
-- duplicate the Records page. Same pattern as REP-003 over FRM-002.
--
-- *** sourceStatus IS "all", NOT THE DEFAULT "submitted". *** This is the one decision on this
-- migration that could quietly break the deliverable. A CAPA is a draft entry for as long as it is
-- being worked - which is exactly the period a register exists to show. Under the default, an open
-- CAPA would be invisible until the day it closed, so the register would list only finished work
-- and answer the opposite of the question it is for. REP-003 uses "submitted" correctly, because a
-- complaint log lists complaints that have been filed; the two are genuinely different.
--
-- THE STATUS COLUMN IS A `cases` RULE AND ORDER MATTERS - first match wins:
--   closure_date is not empty                      -> Closed
--   verification_result = "Not effective ..."       -> Reopened
--   verification_result = "Effective ..."           -> Verified - awaiting closure
--   root_cause is not empty                         -> Under investigation
--   correction_taken is not empty                   -> Contained
--   otherwise                                       -> Open
-- Closed is tested first on purpose: a CAPA that was reopened and later closed is Closed, not
-- Reopened. All six states were driven through the real resolveReportColumns() before this was
-- written; none of them is assumed.
--
-- THE TWO `equals` VALUES ARE EXACT MATCHES ON FRM-007 SELECT OPTIONS, em dashes and all. That is
-- why FRM-007 and REP-007 are generated by ONE script from shared constants: authored separately, a
-- single changed word or dash on either side would break the column with no error anywhere - it
-- would simply always fall through to its default, and a register showing every CAPA as "Under
-- investigation" looks plausible enough to go unnoticed. The generator asserts every case value is
-- an option the source select actually offers, and that every column and param names a field
-- FRM-007 actually has.
--
-- NO FIXED filters[]. Every CAPA belongs on the register - unlike REP-201, which is an Approved
-- Supplier Register and must exclude the unapproved.
--
-- Inserted as status='draft'; approved and activated with FSQM-009 and FRM-007. Guarded on
-- non-existence, and on FRM-007 existing - a report whose source does not exist renders empty with
-- no error, which is the FSQM-022 Form-0010 failure in a different costume.

