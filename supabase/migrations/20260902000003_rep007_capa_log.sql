declare
  r record;
begin
  select status, type,
         content->'report_schema'->>'sourceSopNumber'                        as src,
         content->'report_schema'->>'sourceStatus'                           as src_status,
         content->'report_schema'->>'defaultDateField'                       as date_field,
         jsonb_array_length(content->'report_schema'->'columns')             as cols,
         jsonb_array_length(content->'report_schema'->'params')              as params,
         jsonb_array_length(content->'report_schema'->'legend')              as legend,
         (select jsonb_array_length(c->'source'->'cases')
            from jsonb_array_elements(content->'report_schema'->'columns') c
           where c->>'id' = 'status')                                        as status_cases,
         (select c->'source'->'cases'->0->>'field'
            from jsonb_array_elements(content->'report_schema'->'columns') c
           where c->>'id' = 'status')                                        as first_case
    into r
    from public.sop_documents where sop_number = 'REP-007';

  if r.status <> 'draft' or r.type <> 'report' then
    raise exception 'REP-007 wrong metadata: status=%, type=%.', r.status, r.type;
  end if;
  if r.src <> 'FRM-007' then
    raise exception 'REP-007 sources from % rather than FRM-007.', r.src;
  end if;
  -- the decision this whole migration turns on
  if r.src_status is distinct from 'all' then
    raise exception 'REP-007 sourceStatus is % - open CAPAs would be invisible until closed.',
      coalesce(r.src_status, 'unset (defaults to submitted)');
  end if;
  if r.cols <> 12 or r.params <> 4 or r.legend <> 3 then
    raise exception 'REP-007 wrong shape: % columns, % params, % legend lines (expected 12 / 4 / 3).',
      r.cols, r.params, r.legend;
  end if;
  if r.date_field <> 'date_raised' then
    raise exception 'REP-007 defaultDateField is %, expected date_raised.', r.date_field;
  end if;
  -- Closed must be tested first: a reopened-then-closed CAPA is Closed, not Reopened
  if r.status_cases <> 5 or r.first_case <> 'closure_date' then
    raise exception 'REP-007 status rules wrong: % cases, first tests % (expected 5 / closure_date).',
      r.status_cases, r.first_case;
  end if;
end $$;

